from pathlib import Path
from typing import Protocol

from printforge.domain.planning import PrintSpec


class Upscaler(Protocol):
    def upscale(self, source: Path, destination: Path) -> None: ...


class ImageProcessor(Protocol):
    def inspect(self, source: Path, max_pixels: int | None = None) -> dict[str, object]: ...
    def normalize(self, source: Path, destination: Path) -> None: ...
    def export(self, source: Path, destination: Path, spec: "PrintSpec", fmt: str) -> None: ...
    def crop(self, source: Path, destination: Path, box: tuple[int, int, int, int]) -> None: ...
    def resize(self, source: Path, destination: Path, size: tuple[int, int]) -> None: ...
    def content_box(self, source: Path) -> tuple[int, int, int, int]: ...
